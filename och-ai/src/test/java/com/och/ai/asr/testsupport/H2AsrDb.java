package com.och.ai.asr.testsupport;

import com.baomidou.mybatisplus.core.MybatisConfiguration;
import com.baomidou.mybatisplus.extension.plugins.MybatisPlusInterceptor;
import com.baomidou.mybatisplus.extension.plugins.inner.PaginationInnerInterceptor;
import com.baomidou.mybatisplus.extension.spring.MybatisSqlSessionFactoryBean;
import com.och.ai.asr.mapper.CallTranscriptMapper;
import com.och.ai.asr.mapper.CallTranscriptSegmentMapper;
import com.och.ai.asr.service.IAsrTranscriptService;
import com.och.ai.asr.service.impl.AsrTranscriptServiceImpl;
import org.apache.ibatis.datasource.unpooled.UnpooledDataSource;
import org.apache.ibatis.session.SqlSession;
import org.apache.ibatis.session.SqlSessionFactory;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.Statement;

/**
 * H2 内存库测试支撑（方案 11.2 P0 前端与存储闭环）。
 *
 * <p>用 H2(PostgreSQL 兼容模式) 真实建表 + MyBatis-Plus 真实持久化，
 * <b>不触碰生产 KingbaseES</b>（规则：不改生产/不污染系统数据）。
 * 供持久化与端到端一致性测试复用。</p>
 */
public final class H2AsrDb implements AutoCloseable {

    private final SqlSessionFactory sessionFactory;
    private final SqlSession session;
    private final CallTranscriptMapper transcriptMapper;
    private final CallTranscriptSegmentMapper segmentMapper;
    private final AsrTranscriptServiceImpl transcriptService;

    private H2AsrDb(SqlSessionFactory sf, SqlSession session,
                    CallTranscriptMapper tm, CallTranscriptSegmentMapper sm,
                    AsrTranscriptServiceImpl svc) {
        this.sessionFactory = sf;
        this.session = session;
        this.transcriptMapper = tm;
        this.segmentMapper = sm;
        this.transcriptService = svc;
    }

    public static H2AsrDb create() throws Exception {
        DataSource ds = new UnpooledDataSource(
                "org.h2.Driver",
                "jdbc:h2:mem:asrit_" + System.nanoTime() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", "");

        MybatisSqlSessionFactoryBean fb = new MybatisSqlSessionFactoryBean();
        fb.setDataSource(ds);
        MybatisPlusInterceptor interceptor = new MybatisPlusInterceptor();
        interceptor.addInnerInterceptor(new PaginationInnerInterceptor(com.baomidou.mybatisplus.annotation.DbType.H2));
        fb.setPlugins(interceptor);
        SqlSessionFactory sf = fb.getObject();
        // 注册 Mapper（MybatisConfiguration 支持 BaseMapper 注入）
        MybatisConfiguration cfg = (MybatisConfiguration) sf.getConfiguration();
        cfg.addMapper(CallTranscriptMapper.class);
        cfg.addMapper(CallTranscriptSegmentMapper.class);

        // 建表（H2/PG 兼容：IDENTITY 自增）
        createSchema(ds);

        SqlSession session = sf.openSession(true); // autocommit
        CallTranscriptMapper tm = session.getMapper(CallTranscriptMapper.class);
        CallTranscriptSegmentMapper sm = session.getMapper(CallTranscriptSegmentMapper.class);
        AsrTranscriptServiceImpl svc = new AsrTranscriptServiceImpl(tm, sm);
        return new H2AsrDb(sf, session, tm, sm, svc);
    }

    private static void createSchema(DataSource ds) throws Exception {
        String ddl = """
                CREATE TABLE call_transcript (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    call_id VARCHAR(64) NOT NULL,
                    unique_id VARCHAR(128),
                    caller_number VARCHAR(64),
                    callee_number VARCHAR(64),
                    agent_id BIGINT,
                    agent_number VARCHAR(64),
                    agent_name VARCHAR(128),
                    direction SMALLINT,
                    provider VARCHAR(32),
                    sample_rate INT,
                    full_text TEXT,
                    segment_count INT,
                    char_count INT,
                    start_time TIMESTAMP,
                    end_time TIMESTAMP,
                    duration_ms BIGINT,
                    status VARCHAR(16) NOT NULL,
                    error_code VARCHAR(32),
                    error_msg VARCHAR(512),
                    record_url VARCHAR(512),
                    first_text_latency_ms BIGINT,
                    final_latency_ms BIGINT,
                    reconnect_count INT,
                    create_by BIGINT,
                    create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    update_by BIGINT,
                    update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    del_flag SMALLINT DEFAULT 0
                );
                CREATE TABLE call_transcript_segment (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    transcript_id BIGINT,
                    call_id VARCHAR(64) NOT NULL,
                    segment_id VARCHAR(128) NOT NULL,
                    seq INT,
                    speaker VARCHAR(16),
                    text TEXT NOT NULL,
                    is_final SMALLINT DEFAULT 1,
                    begin_ms BIGINT,
                    end_ms BIGINT,
                    confidence DOUBLE PRECISION,
                    provider VARCHAR(32)
                );
                """;
        try (Connection c = ds.getConnection(); Statement st = c.createStatement()) {
            for (String sql : ddl.split(";")) {
                String s = sql.trim();
                if (!s.isEmpty()) {
                    st.execute(s);
                }
            }
        }
    }

    public IAsrTranscriptService service() {
        return transcriptService;
    }

    public AsrTranscriptServiceImpl serviceImpl() {
        return transcriptService;
    }

    public CallTranscriptMapper transcriptMapper() {
        return transcriptMapper;
    }

    public CallTranscriptSegmentMapper segmentMapper() {
        return segmentMapper;
    }

    public SqlSessionFactory sessionFactory() {
        return sessionFactory;
    }

    @Override
    public void close() {
        if (session != null) {
            session.close();
        }
    }
}
